BEGIN;
SELECT count(*) = 1 AS protection_registered
FROM pg_settings
WHERE name = 'supautils.reserved_role_members' AND context = 'sighup';
CREATE ROLE supabase_warehouse_writer NOLOGIN;
CREATE ROLE supabase_warehouse_writer_test NOLOGIN IN ROLE supabase_warehouse_writer;
CREATE ROLE warehouse_writer_test_login LOGIN;
GRANT supabase_warehouse_writer_test TO warehouse_writer_test_login;
SET ROLE postgres;
SAVEPOINT denied;
GRANT supabase_warehouse_writer_test TO postgres;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
GRANT warehouse_writer_test_login TO postgres;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
GRANT pg_write_all_data TO postgres;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
ALTER ROLE pg_write_all_data LOGIN;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
ALTER ROLE supabase_warehouse_writer_test LOGIN;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
COMMENT ON ROLE supabase_warehouse_writer_test IS 'forged';
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
DROP ROLE supabase_warehouse_writer_test;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
REVOKE supabase_warehouse_writer_test FROM warehouse_writer_test_login;
ROLLBACK TO SAVEPOINT denied;
SAVEPOINT denied;
REVOKE supabase_warehouse_writer FROM supabase_warehouse_writer_test;
ROLLBACK TO SAVEPOINT denied;
RESET ROLE;
REVOKE supabase_warehouse_writer_test FROM warehouse_writer_test_login;
SELECT pg_has_role('warehouse_writer_test_login', 'supabase_warehouse_writer_test', 'MEMBER') AS still_authorized;
DROP ROLE warehouse_writer_test_login;
DROP ROLE supabase_warehouse_writer_test;
DROP ROLE supabase_warehouse_writer;
ROLLBACK;
